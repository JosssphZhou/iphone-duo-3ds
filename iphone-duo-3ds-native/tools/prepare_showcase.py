#!/usr/bin/env python3
"""Compile the browser's pixel/hit-region contract into per-page native atlases."""
import json,shutil,sys,math
from PIL import Image
from pathlib import Path
import argparse
from asset_config import asset_dir
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('source',nargs='?',type=Path,default=asset_dir('music-store-assets'));args=parser.parse_args()
src=args.source
j=json.loads((src/'manifest.json').read_text())
if j.get('version')!=1:raise ValueError('Unsupported showcase manifest version')
seen=set()
for p in j['pages']:
 key=(p['route'],p['variant'])
 if key in seen:raise ValueError('Duplicate page '+str(key))
 seen.add(key)
 for orient,size in [('landscape',[(400,240),(320,240)]),('portrait',[(240,400),(240,320)])]:
  for screen,(w,h) in zip(['top','bottom'],size):
   from PIL import Image
   v=p['views'][orient][screen]
   if Image.open(src/v['image']).size!=(w,h):raise ValueError('Invalid screen size '+v['image'])
   for r in v['regions']:
    if screen=='bottom' and not (r['w']>0 and r['h']>0 and r['x']>=0 and r['y']>=0 and r['x']+r['w']<=w+1 and r['y']+r['h']<=h+1):raise ValueError('Invalid hit region '+str(r))
out=['/* Generated by tools/prepare_showcase.py. */','#include "showcase_assets.h"']
pages=[]
def color(value):
 if value=='transparent':return 0
 value=value.lstrip('#')
 return int(value[0:2],16)|(int(value[2:4],16)<<8)|(int(value[4:6],16)<<16)|((int(value[6:8],16) if len(value)==8 else 255)<<24)
def rect(r):return '{'+','.join(str(r[k]) for k in ['x','y','w','h'])+'}'
def regions(name,rs):
 if not rs:return 'NULL',0
 out.append('static const ShowRegion '+name+'[]={'+','.join('{'+rect(r)+','+json.dumps(r['action'])+'}' for r in rs)+'};')
 return name,len(rs)
for pi,p in enumerate(j['pages']):
 images=[]
 generated={}
 def img(file):
  if not file:return -1
  if file not in images:images.append(file)
  return images.index(file)
 views=[]
 for vi,(orient,screen) in enumerate([('landscape','top'),('landscape','bottom'),('portrait','top'),('portrait','bottom')]):
  v=p['views'][orient][screen];im=img(v['image']);ov=v.get('overlays',{});opened=ov.get('opened',{})
  oi=img(opened.get('image'));orn,orc=regions(f'p{pi}v{vi}open',opened.get('regions',[]));rn,rc=regions(f'p{pi}v{vi}regions',v['regions']);ovs=[]
  for kind,o in sorted(ov.items(),key=lambda pair:pair[0]!='miniplayer'):
   if kind=='opened' or (kind in ('track-title','cover') and 'miniplayer' in ov):continue
   for o in (o if isinstance(o,list) else [o]):
    ids=[-1]*9
    if kind=='miniplayer':
     for variant in o['variants']:ids[variant['album']*3+variant['track']]=img(variant['image'])
    elif kind=='play':ids=[img(o['paused']),img(o['playing']),-1]
    elif kind=='get':ids=[img(o[k]) for k in ['idle','installing','open']]
    elif kind in ('shuffle','repeat'):ids=[img(o.get('off')),img(o.get('on')),-1]
    elif kind not in ('progress','elapsed','remaining'):raise ValueError(kind)
    colors=[color(o.get('background','#ffffff')),color(o.get('foreground',o.get('fill','#8e8e93'))),color(o.get('track','#d6d6dc'))]
    bgrect=o['rect']
    if kind=='progress':
     # The browser's 3px background patch does not erase its baked thumb.
     # Reconstruct a wider clean band from the adjacent unobstructed rows.
     base=Image.open(src/v['image']).convert('RGBA')
     r=o['rect'];x0=math.floor(r['x']);x1=math.ceil(r['x']+r['w'])
     y0=max(1,math.floor(r['y'])-4);y1=min(base.height-1,math.ceil(r['y']+r['h'])+4)
     clean=Image.new('RGBA',(x1-x0,y1-y0))
     for yy in range(y1-y0):
      t=(yy+1)/(y1-y0+1)
      for xx in range(x1-x0):
       a=base.getpixel((x0+xx,y0-1));b=base.getpixel((x0+xx,y1))
       clean.putpixel((xx,yy),tuple(round(a[c]*(1-t)+b[c]*t) for c in range(4)))
     name=Path(v['image']).stem+'_progress_clean.png';generated[name]=clean
     bgimg=img(name);bgrect=dict(x=x0,y=y0,w=x1-x0,h=y1-y0)
    else:bgimg=img(o.get('backgroundImage'))
    ovs.append('{'+rect(o['rect'])+',SHOW_OVERLAY_'+kind.upper()+',{'+','.join(map(str,ids))+'},'+','.join(str(c)+'u' for c in colors)+','+str(bgimg)+','+rect(bgrect)+','+str(o.get('app',-1))+'}')
  on=f'p{pi}v{vi}overlays'
  if ovs:out.append('static const ShowOverlay '+on+'[]={'+','.join(ovs)+'};')
  views.append('{'+f'{im},{oi},{orn},{orc},{rn},{rc},'+(on if ovs else 'NULL')+','+str(len(ovs))+'}')
 atlas=f'showcase_{pi}'
 (root/'gfx'/f'{atlas}.t3s').write_text('--atlas --border=edge -f rgba8888 -z auto\n'+'\n'.join('showcase/'+f for f in images)+'\n')
 (root/'gfx'/'showcase').mkdir(exist_ok=True)
 for f in images:
  if f in generated:generated[f].save(root/'gfx'/'showcase'/f)
  else:shutil.copy2(src/f,root/'gfx'/'showcase'/f)
 pages.append('{'+json.dumps(p['route'])+','+str(p['variant'])+','+json.dumps('romfs:/gfx/'+atlas+'.t3x')+',{'+','.join(views)+'}}')
out.append('const ShowPageAssets showPages[]={'+','.join(pages)+'};')
out.append('const size_t showPageCount=sizeof(showPages)/sizeof(showPages[0]);')
(root/'source'/'showcase_assets.c').write_text('\n'.join(out)+'\n')
actions=sorted({r['action'] for p in j['pages'] for orient in p['views'].values() for v in orient.values() for r in v['regions']})
(root/'tests'/'showcase_contract_actions.h').write_text('/* Generated from final browser regions. */\nstatic const char *contractActions[]={'+','.join(json.dumps(a) for a in actions)+'};\n')
shutil.copy2(src/'manifest.json',root/'showcase-manifest.json')
print('Generated',len(pages),'pages and',len(actions),'actions')
